package migrate

import (
	"errors"
	"fmt"
	"strings"
)

const lockTable = "__mist_lock"

// engine is the SQL for one database this repository migrates.
// pg, mysql, sqlite, oracle, mssql, and dm are the known names. A new database is added in this repository.
type engine struct {
	name string
}

func engineFor(name string) (engine, error) {
	switch name {
	case "pg", "postgres":
		return engine{name: "pg"}, nil
	case "mysql":
		return engine{name: "mysql"}, nil
	case "sqlite":
		return engine{name: "sqlite"}, nil
	case "oracle":
		return engine{name: "oracle"}, nil
	case "mssql":
		return engine{name: "mssql"}, nil
	case "dm":
		return engine{name: "dm"}, nil
	default:
		return engine{}, fmt.Errorf("migrate: driver %q is not pg, mysql, sqlite, oracle, mssql, or dm", name)
	}
}

func (e engine) normalize(cfg Config) (string, string, error) {
	schema := cfg.Schema
	if schema == "" {
		switch e.name {
		case "sqlite":
			schema = "main"
		case "oracle", "dm":
			schema = ""
		case "mssql":
			schema = "dbo"
		default:
			schema = defaultSchema
		}
	}
	if e.name == "sqlite" && schema != "main" {
		return "", "", fmt.Errorf("migrate: sqlite has no schema %q", schema)
	}
	table := cfg.Table
	if table == "" {
		table = defaultTable
	}
	if (schema != "" && !identRE.MatchString(schema)) || !identRE.MatchString(table) {
		return "", "", fmt.Errorf("migrate: schema %q or table %q is not a safe identifier", schema, table)
	}
	return schema, table, nil
}

func (e engine) qual(schema, table string) string {
	if e.name == "sqlite" || ((e.name == "oracle" || e.name == "dm") && schema == "") {
		return quoteIdent(table)
	}
	if e.name == "mssql" {
		return e.quote(schema) + "." + e.quote(table)
	}
	q := quoteIdent
	if e.name == "mysql" {
		q = quoteBacktick
	}
	return q(schema) + "." + q(table)
}

func (e engine) ph(n int) string {
	switch e.name {
	case "pg":
		return fmt.Sprintf("$%d", n)
	case "oracle":
		return fmt.Sprintf(":%d", n)
	case "dm":
		return "?"
	case "mssql":
		return fmt.Sprintf("@p%d", n)
	default:
		return "?"
	}
}

func (e engine) schemaSQL(schema string) string {
	switch e.name {
	case "sqlite":
		return ""
	case "mysql":
		return "CREATE DATABASE IF NOT EXISTS " + quoteBacktick(schema)
	case "oracle", "dm":
		return ""
	case "mssql":
		if schema == "dbo" {
			return ""
		}
		return "IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'" + schema + "') EXEC(N'CREATE SCHEMA " + e.quote(schema) + "')"
	default:
		return "CREATE SCHEMA IF NOT EXISTS " + quoteIdent(schema)
	}
}

func (e engine) createTable(schema, table string) string {
	switch e.name {
	case "mysql":
		return fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s (
				id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
				hash text NOT NULL,
				created_at bigint,
				name text,
				applied_at timestamp NULL DEFAULT CURRENT_TIMESTAMP
			)`, e.qual(schema, table))
	case "sqlite":
		return fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s (
				id integer PRIMARY KEY,
				hash text NOT NULL,
				created_at integer,
				name text,
				applied_at text DEFAULT CURRENT_TIMESTAMP
			)`, e.qual(schema, table))
	case "oracle":
		return fmt.Sprintf(`CREATE TABLE %s (
				"id" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				"hash" VARCHAR2(64) NOT NULL,
				"created_at" NUMBER(19),
				"name" VARCHAR2(4000),
				"applied_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP
			)`, e.qual(schema, table))
	case "dm":
		return fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s (
				"id" BIGINT IDENTITY(1,1) PRIMARY KEY,
				"hash" VARCHAR(64) NOT NULL,
				"created_at" BIGINT,
				"name" VARCHAR(8188),
				"applied_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP
			)`, e.qual(schema, table))
	case "mssql":
		return fmt.Sprintf(`IF OBJECT_ID(N'%s', N'U') IS NULL CREATE TABLE %s (
				%s bigint IDENTITY(1,1) PRIMARY KEY,
				%s nvarchar(64) NOT NULL,
				%s bigint NULL,
				%s nvarchar(4000) NULL,
				%s datetime2 NULL DEFAULT sysdatetime()
			)`, strings.ReplaceAll(e.qual(schema, table), "'", "''"), e.qual(schema, table),
			e.quote("id"), e.quote("hash"), e.quote("created_at"), e.quote("name"), e.quote("applied_at"))
	default:
		return CreateTableSQL(schema, table)
	}
}

// prepare runs before the transaction. SQLite creates the lock table here.
// The write that takes the lock runs inside the transaction.
func (e engine) prepare(schema, table string) []string {
	if e.name != "sqlite" {
		return nil
	}
	return []string{
		fmt.Sprintf(`CREATE TABLE IF NOT EXISTS %s (name text NOT NULL PRIMARY KEY)`, quoteIdent(lockTable)),
	}
}

// txLock is the statement that runs inside the transaction before reading applied names.
// MySQL holds GET_LOCK on the connection instead, because DDL commits the transaction.
func (e engine) txLock(schema, table string) (string, []any) {
	switch e.name {
	case "pg":
		return "select pg_advisory_xact_lock($1)", []any{advisoryKey(schema, table)}
	case "mssql":
		return "EXEC sp_getapplock @p1, 'Exclusive', 'Transaction', -1", []any{fmt.Sprintf("mist:%d", advisoryKey(schema, table))}
	case "sqlite":
		return fmt.Sprintf(
			`insert into %s (name) values (?) on conflict(name) do update set name = excluded.name`,
			quoteIdent(lockTable),
		), []any{table}
	default:
		return "", nil
	}
}

func (e engine) preamble() string {
	if e.name == "sqlite" {
		return "PRAGMA busy_timeout = 60000"
	}
	return ""
}

func (e engine) columnsSQL(schema, table string) (string, []any) {
	switch e.name {
	case "sqlite":
		return fmt.Sprintf("select name from pragma_table_info(%s)", quoteLiteral(table)), nil
	case "mysql":
		return "select column_name from information_schema.columns where table_schema = ? and table_name = ? order by ordinal_position", []any{schema, table}
	case "oracle":
		if schema == "" {
			return `select column_name from all_tab_columns where owner = sys_context('USERENV','CURRENT_SCHEMA') and table_name = :1 order by column_id`, []any{table}
		}
		return `select column_name from all_tab_columns where owner = :1 and table_name = :2 order by column_id`, []any{schema, table}
	case "dm":
		if schema == "" {
			return `select column_name from all_tab_columns where owner = sys_context('USERENV','CURRENT_SCHEMA') and table_name = ? order by column_id`, []any{table}
		}
		return `select column_name from all_tab_columns where owner = ? and table_name = ? order by column_id`, []any{schema, table}
	case "mssql":
		return "select column_name from information_schema.columns where table_schema = @p1 and table_name = @p2 order by ordinal_position", []any{schema, table}
	default:
		return "select column_name from information_schema.columns where table_schema = $1 and table_name = $2 order by ordinal_position", []any{schema, table}
	}
}

func (e engine) appliedSQL(schema, table string) string {
	return fmt.Sprintf("select %s, %s from %s", e.quote("hash"), e.quote("name"), e.qual(schema, table))
}

func (e engine) deleteSQL(schema, table string) string {
	return fmt.Sprintf("delete from %s where %s = %s", e.qual(schema, table), e.quote("name"), e.ph(1))
}

func (e engine) insertSQL(schema, table string) string {
	return fmt.Sprintf(
		"insert into %s (%s, %s, %s) values (%s, %s, %s)",
		e.qual(schema, table),
		e.quote("hash"), e.quote("created_at"), e.quote("name"),
		e.ph(1), e.ph(2), e.ph(3),
	)
}

func (e engine) quote(name string) string {
	switch e.name {
	case "mysql":
		return quoteBacktick(name)
	case "mssql":
		return "[" + strings.ReplaceAll(name, "]", "]]") + "]"
	default:
		return quoteIdent(name)
	}
}

func (e engine) retryable(err error) bool {
	if err == nil {
		return false
	}
	switch e.name {
	case "pg":
		var state interface{ SQLState() string }
		return errors.As(err, &state) && state.SQLState() == "23505"
	case "mysql":
		msg := err.Error()
		return strings.Contains(msg, "Error 1062") || strings.Contains(msg, "Error 1007") || strings.Contains(msg, "Error 1050")
	case "oracle":
		msg := err.Error()
		return strings.Contains(msg, "ORA-00955") || strings.Contains(msg, "ORA-01920")
	case "dm":
		msg := err.Error()
		return strings.Contains(msg, "已存在") || strings.Contains(msg, "-2116") || strings.Contains(msg, "already exists")
	case "mssql":
		msg := err.Error()
		return strings.Contains(msg, "already an object named") || strings.Contains(msg, "already exists")
	default:
		return false
	}
}

func quoteBacktick(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}

func quoteLiteral(name string) string {
	return "'" + strings.ReplaceAll(name, "'", "''") + "'"
}
