package codegen

import (
	"fmt"
	"go/format"
	"strings"
)

func emit(pkg string, tables []table) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by drizzle-go. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n")
	if needsTime(tables) {
		b.WriteString("\t\"time\"\n\n")
	}
	b.WriteString("\t\"github.com/xbmlz/drizzle-go/pg\"\n)\n\n")
	for i, t := range tables {
		if i > 0 {
			b.WriteByte('\n')
		}
		writeTable(&b, t)
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("codegen: format generated source: %w\n%s", err, b.String())
	}
	return src, nil
}

func needsTime(tables []table) bool {
	for _, t := range tables {
		for _, c := range t.cols {
			if strings.Contains(c.goType, "time.") {
				return true
			}
		}
	}
	return false
}

func writeTable(b *strings.Builder, t table) {
	st := unexport(t.typeName) + "Table"
	fmt.Fprintf(b, "type %s struct {\n\tpg.TableBase\n", st)
	for _, c := range t.cols {
		fmt.Fprintf(b, "\t%s pg.Col[%s, %s]\n", c.field, t.typeName, c.goType)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func scan%s(row pg.Row, dst *%s) error {\n\treturn row.Scan(", t.typeName, t.typeName)
	for i, c := range t.cols {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "&dst.%s", c.field)
	}
	b.WriteString(")\n}\n\n")

	fmt.Fprintf(b, "func (%s) Scan(row pg.Row, dst *%s) error {\n\treturn scan%s(row, dst)\n}\n\n", st, t.typeName, t.typeName)

	fmt.Fprintf(b, "var %s = %s{\n\tTableBase: pg.TableBase{SQLName: %q},\n", t.varName, st, t.sqlName)
	for _, c := range t.cols {
		fmt.Fprintf(b, "\t%s: pg.Col[%s, %s]{\n\t\tTable: %q,\n\t\tName: %q,\n\t\tPtr: func(v *%s) any { return &v.%s },\n\t},\n",
			c.field, t.typeName, c.goType, t.sqlName, c.colName, t.typeName, c.field)
	}
	b.WriteString("}\n")
}

func unexport(name string) string {
	return strings.ToLower(name[:1]) + name[1:]
}
