package codegen

import (
	"fmt"
	"go/format"
	"strings"
)

func emit(pkg string, tables []table) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by mist. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n")
	if needsJSON(tables) {
		b.WriteString("\t\"encoding/json\"\n")
	}
	if needsTime(tables) {
		b.WriteString("\t\"time\"\n")
	}
	if needsJSON(tables) || needsTime(tables) {
		b.WriteByte('\n')
	}
	dialect := "pg"
	if len(tables) > 0 && tables[0].dialect == "mysql" {
		dialect = "mysql"
	}
	fmt.Fprintf(&b, "\t\"github.com/go-mist/mist/%s\"\n", dialect)
	if needsCodecs(tables) {
		fmt.Fprintf(&b, "\t\"github.com/go-mist/mist/%s/codecs\"\n", dialect)
	}
	b.WriteString("\t\"github.com/go-mist/mist/sql\"\n)\n\n")
	for i, t := range tables {
		if i > 0 {
			b.WriteByte('\n')
		}
		writeTable(&b, t)
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("codegen: format generated source: %w\n%s", err, b.String())
	}
	return src, nil
}

func needsJSON(tables []table) bool {
	for _, t := range tables {
		for _, c := range t.cols {
			if strings.Contains(c.goType, "json.") {
				return true
			}
		}
	}
	return false
}

func needsCodecs(tables []table) bool {
	for _, t := range tables {
		for _, c := range t.cols {
			if codecExpr(c, t.dialect) != "" {
				return true
			}
		}
	}
	return false
}

func needsTime(tables []table) bool {
	for _, t := range tables {
		for _, c := range t.cols {
			if strings.Contains(c.goType, "time.") {
				return true
			}
		}
	}
	return false
}

func writeTable(b *strings.Builder, t table) {
	q := "pg"
	if t.dialect == "mysql" {
		q = "mysql"
	}
	st := unexport(t.typeName) + "Table"
	fmt.Fprintf(b, "type %s struct {\n\t%s.TableBase\n", st, q)
	for _, c := range t.cols {
		fmt.Fprintf(b, "\t%s %s.Col[%s, %s]\n", c.field, q, t.typeName, c.goType)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func scan%s(row %s.Row, dst *%s) error {\n\treturn row.Scan(", t.typeName, q, t.typeName)
	for i, c := range t.cols {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "&dst.%s", c.path)
	}
	b.WriteString(")\n}\n\n")

	fmt.Fprintf(b, "func (%s) Scan(row %s.Row, dst *%s) error {\n\treturn scan%s(row, dst)\n}\n\n", st, q, t.typeName, t.typeName)
	fmt.Fprintf(b, "// Row binds this table to row type %s so the query builder can check it at compile time.\n", t.typeName)
	fmt.Fprintf(b, "func (%s) Row() *%s { return nil }\n\n", st, t.typeName)
	fmt.Fprintf(b, "// Columns are the full-row select list, in the same order as scan%s.\n", t.typeName)
	fmt.Fprintf(b, "func (t %s) Columns() []sql.Chunk {\n\treturn []sql.Chunk{", st)
	for i, c := range t.cols {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "t.%s", c.field)
	}
	b.WriteString("}\n}\n\n")
	writePrimaryKey(b, st, t.primary)
	writeIndexes(b, q, st, t.indexes)
	writeChecks(b, q, st, t.checks)
	writeColumnSpecs(b, q, st, t)

	fmt.Fprintf(b, "var %s = %s{\n\tTableBase: %s.TableBase{SQLName: %q},\n", t.varName, st, q, t.sqlName)
	for _, c := range t.cols {
		fmt.Fprintf(b, "\t%s: %s.Col[%s, %s]{\n\t\tTable: %q,\n\t\tName: %q,\n\t\tPtr: func(v *%s) any { return &v.%s },\n",
			c.field, q, t.typeName, c.goType, t.sqlName, c.colName, t.typeName, c.path)
		if expr := codecGo(c, t.dialect, t.sqlName); expr != "" {
			fmt.Fprintf(b, "\t\tCodec: %s,\n", expr)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
}

func codecGo(c column, dialect, table string) string {
	expr := codecExpr(c, dialect)
	if expr == "" {
		return ""
	}
	return fmt.Sprintf("%s.At(%q)", expr, table)
}

func codecExpr(c column, dialect string) string {
	if dialect == "mysql" {
		switch c.sqlType {
		case "numeric", "decimal":
			return fmt.Sprintf("codecs.Decimal.Bind(%q)", c.colName)
		case "json":
			return fmt.Sprintf("codecs.JSON.Bind(%q)", c.colName)
		case "datetime", "timestamp", "date", "time":
			return fmt.Sprintf("codecs.DateTime.Bind(%q)", c.colName)
		case "blob":
			return fmt.Sprintf("codecs.Blob.Bind(%q)", c.colName)
		default:
			return ""
		}
	}
	if c.enumName != "" {
		return fmt.Sprintf("codecs.Enum{Name: %q}.Bind(%q)", c.enumName, c.colName)
	}
	base, dims := splitArray(c.sqlType)
	if dims > 0 {
		return fmt.Sprintf("codecs.Array{BaseType: %q, Dimensions: %d}.Bind(%q)", base, dims, c.colName)
	}
	switch base {
	case "numeric", "decimal":
		return fmt.Sprintf("codecs.Numeric.Bind(%q)", c.colName)
	case "jsonb":
		return fmt.Sprintf("codecs.JSONB.Bind(%q)", c.colName)
	case "json":
		return fmt.Sprintf("codecs.JSON.Bind(%q)", c.colName)
	case "bytea":
		return fmt.Sprintf("codecs.Bytea.Bind(%q)", c.colName)
	case "interval":
		return fmt.Sprintf("codecs.Interval.Bind(%q)", c.colName)
	case "uuid":
		return fmt.Sprintf("codecs.UUID.Bind(%q)", c.colName)
	case "date":
		return fmt.Sprintf("codecs.Date.Bind(%q)", c.colName)
	case "time":
		return fmt.Sprintf("codecs.Time.Bind(%q)", c.colName)
	case "timestamp":
		return fmt.Sprintf("codecs.Timestamp.Bind(%q)", c.colName)
	case "timestamptz":
		return fmt.Sprintf("codecs.Timestamptz.Bind(%q)", c.colName)
	default:
		return ""
	}
}

func writePrimaryKey(b *strings.Builder, st string, cols []string) {
	if len(cols) == 0 {
		return
	}
	fmt.Fprintf(b, "func (%s) PrimaryKey() []string {\n\treturn []string{%s}\n}\n\n", st, quotedList(cols))
}

func writeIndexes(b *strings.Builder, q, st string, indexes []indexSpec) {
	if len(indexes) == 0 {
		return
	}
	fmt.Fprintf(b, "func (%s) Indexes() []%s.Index {\n\treturn []%s.Index{\n", st, q, q)
	for _, idx := range indexes {
		fmt.Fprintf(b, "\t\t{Name: %q, Columns: []string{%s}, Unique: %t},\n", idx.name, quotedList(idx.columns), idx.unique)
	}
	b.WriteString("\t}\n}\n\n")
}

func writeColumnSpecs(b *strings.Builder, q, st string, t table) {
	inPK := map[string]struct{}{}
	for _, name := range t.primary {
		inPK[name] = struct{}{}
	}
	fmt.Fprintf(b, "func (%s) ColumnSpecs() []%s.ColumnSpec {\n\treturn []%s.ColumnSpec{\n", st, q, q)
	for _, c := range t.cols {
		_, pk := inPK[c.colName]
		fmt.Fprintf(b, "\t\t{Name: %q, SQLType: %q", c.colName, c.sqlType)
		if c.notNull || c.pk || c.identity || pk {
			b.WriteString(", NotNull: true")
		}
		if pk {
			b.WriteString(", PrimaryKey: true")
		}
		if c.unique {
			b.WriteString(", Unique: true")
		}
		if c.uniqueName != "" {
			fmt.Fprintf(b, ", UniqueName: %q", c.uniqueName)
		}
		if c.def != "" {
			fmt.Fprintf(b, ", Default: %q", c.def)
		}
		if c.refTable != "" {
			fmt.Fprintf(b, ", References: %q", c.refTable+"."+c.refCol)
		}
		if c.onDelete != "" {
			fmt.Fprintf(b, ", OnDelete: %q", c.onDelete)
		}
		if c.onUpdate != "" {
			fmt.Fprintf(b, ", OnUpdate: %q", c.onUpdate)
		}
		if c.length > 0 {
			fmt.Fprintf(b, ", Length: %d", c.length)
		}
		if c.precision > 0 {
			fmt.Fprintf(b, ", Precision: %d", c.precision)
		}
		if c.scale > 0 {
			fmt.Fprintf(b, ", Scale: %d", c.scale)
		}
		if c.generated != "" {
			fmt.Fprintf(b, ", Generated: %q", c.generated)
		}
		if c.identity {
			b.WriteString(", Identity: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t}\n}\n\n")
}

func writeChecks(b *strings.Builder, q, st string, checks []checkSpec) {
	if len(checks) == 0 {
		return
	}
	fmt.Fprintf(b, "func (%s) Checks() []%s.Check {\n\treturn []%s.Check{\n", st, q, q)
	for _, chk := range checks {
		fmt.Fprintf(b, "\t\t{Name: %q, Expr: %q},\n", chk.name, chk.expr)
	}
	b.WriteString("\t}\n}\n\n")
}

func quotedList(cols []string) string {
	parts := make([]string, len(cols))
	for i, col := range cols {
		parts[i] = strconvQuote(col)
	}
	return strings.Join(parts, ", ")
}

func strconvQuote(s string) string {
	return fmt.Sprintf("%q", s)
}

func unexport(name string) string {
	return strings.ToLower(name[:1]) + name[1:]
}
