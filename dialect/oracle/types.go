package oracle

import "fmt"

// ColumnType is the Oracle column type for a portable Go field.
// An integer primary key is an identity column. A string with length 0 is VARCHAR2(4000).
func ColumnType(goType string, pk bool, length int) (string, error) {
	switch goType {
	case "int64":
		if pk {
			return "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY", nil
		}
		return "NUMBER(19)", nil
	case "int", "int32":
		if pk {
			return "NUMBER(10) GENERATED BY DEFAULT AS IDENTITY", nil
		}
		return "NUMBER(10)", nil
	case "string":
		if length <= 0 {
			length = 4000
		}
		if length > 4000 {
			return "", fmt.Errorf("oracle: string length %d is above VARCHAR2(4000)", length)
		}
		return fmt.Sprintf("VARCHAR2(%d)", length), nil
	case "bool":
		return "NUMBER(1)", nil
	case "time.Time":
		return "TIMESTAMP", nil
	case "[]byte":
		return "BLOB", nil
	default:
		return "", fmt.Errorf("oracle: %s has no column type", goType)
	}
}
