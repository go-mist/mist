func TestEscape(t *testing.T) {
	d := oracle.Dialect{}
	if got := d.EscapeName(`na"me`); got != `"na""me"` {
		t.Fatal(got)
	}
	if got := d.EscapeParam(0, nil); got != ":1" {
		t.Fatal(got)
	}
	if got := d.EscapeParam(11, nil); got != ":12" {
		t.Fatal(got)
	}
	if got := d.EscapeString("a'b"); got != "'a''b'" {
		t.Fatal(got)
	}
}

func TestBasicSQL(t *testing.T) {
	u := schemafixture.Users
	cases := []struct {
		name string
		sql  string
		run  func() (sql.Query, error)
	}{
		{"select where fetch", `select "users"."id", "users"."name" from "users" where "users"."name" = :1 order by "users"."id" asc fetch next :2 rows only`, func() (sql.Query, error) {
			return oracle.Select(u.ID, u.Name).From(u).Where(op.Eq(u.Name, "alice")).OrderBy(op.Asc(u.ID)).Limit(10).SQL(oracle.Dialect{})
		}},
		{"insert", `insert into "users" ("name") values (:1)`, func() (sql.Query, error) {
			return oracle.Insert(u).Columns(u.Name).Values("ann").SQL(oracle.Dialect{})
		}},
		{"update", `update "users" set "name" = :1 where "users"."id" = :2`, func() (sql.Query, error) {
			return oracle.Update(u).Set(u.Name, "ann").Where(op.Eq(u.ID, int64(1))).SQL(oracle.Dialect{})
		}},
		{"delete", `delete from "users" where "users"."id" = :1`, func() (sql.Query, error) {
			return oracle.Delete(u).Where(op.Eq(u.ID, int64(1))).SQL(oracle.Dialect{})
		}},
		{"join group", `select "users"."id" from "users" inner join "posts" on "posts"."author_id" = "users"."id" group by "users"."id" having "users"."id" > :1 order by "users"."id" asc`, func() (sql.Query, error) {
			return oracle.Select(u.ID).From(u).InnerJoin(schemafixture.Posts, op.Eq(schemafixture.Posts.AuthorID, u.ID)).GroupBy(u.ID).Having(op.Gt(u.ID, int64(1))).OrderBy(op.Asc(u.ID)).SQL(oracle.Dialect{})
		}},
		{"distinct", `select distinct "users"."name" from "users"`, func() (sql.Query, error) {
			return oracle.Select(u.Name).From(u).Distinct().SQL(oracle.Dialect{})
		}},
		{"union", `(select "users"."id" from "users") union (select "users"."id" from "users") order by "id" asc fetch next :1 rows only`, func() (sql.Query, error) {
			return oracle.Select(u.ID).From(u).Union(oracle.Select(u.ID).From(u)).OrderBy(op.Asc(u.ID)).Limit(2).SQL(oracle.Dialect{})
		}},
		{"for update", `select "users"."id" from "users" where "users"."id" = :1 for update nowait`, func() (sql.Query, error) {
			return oracle.Select(u.ID).From(u).Where(op.Eq(u.ID, int64(1))).ForUpdate(query.RowLock{NoWait: true}).SQL(oracle.Dialect{})
		}},
		{"insert select", `insert into "users" ("name") select "posts"."title" from "posts"`, func() (sql.Query, error) {
			return oracle.Insert(u).Columns(u.Name).Select(oracle.Select(schemafixture.Posts.Title).From(schemafixture.Posts)).SQL(oracle.Dialect{})
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := tc.run()
			if err != nil {
				t.Fatal(err)
			}
			if got.SQL != tc.sql {
				t.Fatalf("got %s", got.SQL)
			}
		})
	}
}

func TestUnsupported(t *testing.T) {
	u := schemafixture.Users
	if _, err := oracle.Select(u.ID).From(u).Limit(1).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "order by") {
		t.Fatal(err)
	}
	if _, err := oracle.Insert(u).Columns(u.Name).Values("ann").Returning(u.ID).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "returning") {
		t.Fatal(err)
	}
	if _, err := oracle.Select(u.ID).From(u).Top(1).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "top") {
		t.Fatal(err)
	}
	if _, err := oracle.Insert(u).Columns(u.Name).Values("ann").Output(u.ID).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "output") {
		t.Fatal(err)
	}
	if _, err := oracle.Select(u.ID).From(u).DistinctOn(u.ID).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "distinct on") {
		t.Fatal(err)
	}
	if _, err := oracle.Select(u.ID).From(u).ForShare().SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "for share") {
		t.Fatal(err)
	}
	if _, err := oracle.Insert(u).Columns(u.ID).Values(int64(1)).OnConflictDoNothing(u.ID).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "on conflict") {
		t.Fatal(err)
	}
	if _, err := oracle.Update(u).Set(u.Name, "ann").Limit(1).SQL(oracle.Dialect{}); err == nil || !strings.Contains(err.Error(), "set and where") {
		t.Fatal(err)
	}
}

func TestColumnType(t *testing.T) {
	got, err := oracle.ColumnType("int64", true, 0)
	if err != nil || got != "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY" {
		t.Fatalf("%s %v", got, err)
	}
	got, err = oracle.ColumnType("string", false, 0)
	if err != nil || got != "VARCHAR2(4000)" {
		t.Fatalf("%s %v", got, err)
	}
	got, err = oracle.ColumnType("bool", false, 0)
	if err != nil || got != "NUMBER(1)" {
		t.Fatalf("%s %v", got, err)
	}
	if _, err := oracle.ColumnType("float64", false, 0); err == nil {
		t.Fatal("expected an error")
	}
}
